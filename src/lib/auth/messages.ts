export function localizeAuthMessage(message: string | undefined, locale: AuthLocale) {
  if (!message || locale === 'th') return message
  const throttle = message.match(/^ลองใหม่อีกครั้งในอีก (\d+) นาที$/)
  if (throttle) return `Try again in ${throttle[1]} minute${throttle[1] === '1' ? '' : 's'}.`
  const cooldown = message.match(/^ส่งอีกครั้งได้ใน (\d+) วินาที$/)
  if (cooldown) return `You can resend in ${cooldown[1]} seconds.`
  return englishAuthMessages[message] ?? message
}
